import assert from 'node:assert/strict';
import {faqs,findFaq} from '../src/faq-data.js';
const first=q=>findFaq(q)[0]?.id;
assert.equal(first('Сколько стоит доставка?'),'delivery-cost');
assert.equal(first('Когда получу заказ?'),'delivery-time');
assert.equal(first('Вы доставляете в Казахстан?'),'regions');
assert.equal(first('Подойдет для айфон 12 мини?'),'models');
assert.equal(first('Есть magsafe?'),'magsafe');
assert.equal(first('Как оплатить по QR коду?'),'payment');
assert.equal(first('Чехол не понравился. Могу вернуть?'),'returns');
assert.equal(first('Сколько стоит обратная доставка?'),'return-shipping');
assert.equal(first('Можно вернуть без упаковки?'),'packaging');
assert.equal(first('У меня брак'),'defect');
assert.equal(first('Где мой заказ?'),undefined);
assert.equal(first('Оплатил, деньги списались'),undefined);
assert.equal(first('Хочу оплатить наличными'),undefined);
assert.equal(first('Как статус заказа проверить?'),'tracking');
assert.equal(first('Умеете гравировку?'),undefined);
assert.equal(first('Нужен кредит на чехол'),undefined);
assert.equal(new Set(faqs.map(f=>f.id)).size,faqs.length);
assert.match(faqs.find(f=>f.id==='returns').answer,/7 дней/);
assert.doesNotMatch(faqs.find(f=>f.id==='returns').answer,/5 дней/);
console.log('FAQ routing, product questions and human escalation passed.');
